const shapes = new Map<string, string[]>();
const pathsOf = (name: string) => {
  const key = name in ICONS ? name : "individual";
  let d = shapes.get(key);
  if (!d) shapes.set(key, d = [...ICONS[key].matchAll(/ d="([^"]+)"/g)].map((m) => m[1]));
  return d;
};

export function icon(name: string, size = 20): SVGSVGElement {
  return svg("svg", { width: size, height: size, viewBox: "0 0 256 256", fill: "currentColor", "aria-hidden": "true", class: "icon" },
    pathsOf(name).map((d) => svg("path", { d })));
}

export function viewIcon(view: string, size = 20): SVGSVGElement {
  return icon(VIEW_ICONS[view] ?? "individual", size);
}
